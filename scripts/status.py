"""تطبيع حالة نفاذ الوثيقة إلى قيم مغلقة قابلة للاستعلام.

المشكلة: ``status`` كان نصًّا حرًّا يأتي كما كتبه الموقع المصدر، فاجتمعت في
المُدوَّنة خمس صيغ لمعنى «ملغى» (منها واحدة بخطأ إملائي «إلغي»)، وصيغ
ملوّثة بفواصل منقوطة متسرّبة من دمج أسطر جدول التفاصيل:

    "ساري" · "غير ساري" · "ملغي بصدور نظام الاستثمار …"
    "إلغي هذا النظام بصدور نظام الأسماء التجارية …"
    "غير ساري تم إلغاءه بصدور؛ نظام البيئة؛ "

فأهمّ سؤال يُطرح على مُدوَّنة قانونية — «هل هذا النظام نافذ؟» — لم يكن له
جواب آلي. الحل: حقلان بدل واحد — ``status`` بقيمة من مجموعة مغلقة يتحقق
منها ``lint_corpus``، و``status_note`` يحتفظ بالنصّ الأصلي كاملًا حين
يحمل أكثر من الحالة المجرّدة (جهة الإلغاء، النظام البديل، تاريخه).

قاعدة صريحة: **لا نخترع حالة**. الوثيقة التي لا يذكر مصدرها حالتها لا
يُكتب لها ``status`` إطلاقًا؛ غياب الحقل يعني «غير معروف»، وهو أصدق من
تخمين «نافذ» لـ 82% من المُدوَّنة.
"""

from __future__ import annotations

import re

REPEALED = "ملغى"
AMENDED = "معدّل"
IN_FORCE = "نافذ"

#: القيم المسموح بها في حقل ``status``. غياب الحقل = غير معروف.
VALID_STATUSES = frozenset({IN_FORCE, REPEALED, AMENDED})

# الترتيب مقصود: الإلغاء يغلب النفاذ، لأن نصوصًا كثيرة تقول
# «غير ساري، ألغي بصدور …» — لو فُحص «ساري» أولًا لطابقها خطأً.
_RULES: tuple[tuple[str, re.Pattern[str]], ...] = (
    # ملغ/ألغ/إلغ بكل تصريفاتها وأخطائها الإملائية الملاحظة فعلًا
    (REPEALED, re.compile(r"مل(?:غ|غي|غى|غاة|غية)\b|[أإا]لغ|غير\s+سار|غير\s+ناف")),
    (AMENDED, re.compile(r"مع(?:د|دّ)ل|تم\s+تعديل")),
    (IN_FORCE, re.compile(r"\bسار|\bناف[ذد]")),
)

# النصّ «المجرّد»: حالة بلا تفاصيل إضافية تستحق الحفظ في status_note
_BARE = {
    "ساري", "سارية", "نافذ", "نافذة", "ساري المفعول",
    "غير ساري", "غير سارية", "غير نافذ", "ملغي", "ملغى", "ملغاة",
    "معدل", "معدّل",
}

_WHITESPACE_RE = re.compile(r"\s+")
_TRAILING_JUNK_RE = re.compile(r"[\s؛;,،.\-–—]+$")


def _clean(raw: str) -> str:
    """يزيل الفواصل المنقوطة المتسرّبة من دمج أسطر الجدول والمسافات الزائدة."""
    return _TRAILING_JUNK_RE.sub("", _WHITESPACE_RE.sub(" ", raw).strip())


def normalize_status(raw: str | None) -> tuple[str | None, str | None]:
    """يحوّل نصّ الحالة الخام إلى ``(status, status_note)``.

    - ``status``: قيمة من :data:`VALID_STATUSES`، أو None إن تعذّر التصنيف.
    - ``status_note``: النصّ الأصلي المنظَّف إن كان يحمل تفاصيل زائدة عن
      الحالة المجرّدة، وإلا None (فلا نكرّر «ساري» في حقلين).

    العملية idempotent: تمريرُ ناتجها ثانيةً لا يغيّره.
    """
    if not raw:
        return None, None
    cleaned = _clean(raw)
    if not cleaned:
        return None, None
    for status, pattern in _RULES:
        if pattern.search(cleaned):
            note = None if cleaned in _BARE else cleaned
            return status, note
    # نصّ غير مفهوم: لا نخمّن حالة، لكن لا نفقد النصّ أيضًا
    return None, cleaned
